def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--png", action="store_true")
    ap.add_argument("--strict", action="store_true")
    ap.add_argument("--out", default=str(HERE))
    args = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    errs = gw.check_pinout()
    if errs:
        print("pinout.md cross-check FAILED:\n  " + "\n  ".join(errs))
        return 2
    out = Path(args.out)
    bad = 0
    for name, fn in PICS:
        sh = fn()
        p = out / f"{name}.svg"
        p.write_text(sh.svg(), encoding="utf-8", newline="\n")
        ov = sh.overlaps()
        bad += len(ov)
        print(f"{p.name}: {len(sh.el)} elements, {len(ov)} estimated text overlaps")
        for o in ov:
            print("   ", o)
        if args.png:
            gw.render_png(p, p.with_suffix(".png"))
    return 1 if (args.strict and bad) else 0


if __name__ == "__main__":
    sys.exit(main())
