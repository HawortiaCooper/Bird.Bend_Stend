class Pic(gw.Sheet):
    def frame(self) -> None:
        self.rect(15, 15, gw.W - 30, gw.H - 30, stroke="#222", sw=1.6)
        self.text(30, 52, f"B{self.number} — {self.title}", 22, bold=True, color=gw.C_TITLE)
        self.text(gw.W - 30, 52, "Bird Bend Stand — HW-gate bench pictures", 13, anchor="end", color="#555")

    def title_block(self, x: float = 1005, y: float = 925) -> None:
        w, h = gw.W - 15 - x, gw.H - 15 - y
        self.rect(x, y, w, h, stroke="#222", fill="#fff", sw=1.6)
        self.el.append(f'<line x1="{x}" y1="{y + 28}" x2="{x + w}" y2="{y + 28}" stroke="#222" stroke-width="1"/>')
        self.el.append(f'<line x1="{x + 300}" y1="{y}" x2="{x + 300}" y2="{y + 28}" stroke="#222" stroke-width="1"/>')
        self.text(x + 8, y + 19, "HW-gate bench pictures (D-57)", 13, bold=True, color=gw.C_TITLE)
        self.text(x + 308, y + 19, f"Picture B{self.number} / {N_PICS}", 13, bold=True)
        self.text(x + 8, y + 44, self.title, 11, bold=True)
        self.text(x + 8, y + 59, f"Version {DOC_VERSION} · {gw.DOC_DATE} · owner Implementer A (01_HW)", 10)
        self.text(x + 8, y + 73, "Source: " + SOURCES, 8.5)
        self.text(x + 8, y + 86, "Generated by 01_HW/diagrams/bench/gen_bench_svg.py — do not edit the SVG/PNG", 9,
                  color="#555")
        self.text(x + 8, y + 99, "NOT A CERTIFIED SAFETY DESIGN — bench aid for the HW gate (D-06-GATE)", 9.5,
                  bold=True, color="#b71c1c")

    def note(self, x: float, y: float, rows: list[str], size: float = TS, **kw) -> float:
        return self.lines(x, y, rows, size, 1.32, **kw)

    def probe(self, x: float, y: float, colour: str, label: str = "") -> None:
        """DMM probe tip touching (x, y) from above-left."""
        c = "#d32f2f" if colour == "red" else "#212121"
        self.el.append(f'<line x1="{x - 26:.1f}" y1="{y - 34:.1f}" x2="{x:.1f}" y2="{y:.1f}" stroke="{c}" '
                       f'stroke-width="4" stroke-linecap="round"/>')
        self.circle(x, y, 3, fill=c, stroke="none")
        if label:
            self.text(x - 30, y - 38, label, 10, anchor="end", bold=True, color=c)

    def dmm(self, x: float, y: float, reading: str, mode: str) -> None:
        self.rect(x, y, 128, 62, stroke="#333", fill="#fff7d6", sw=1.4, rx=6)
        self.rect(x + 8, y + 8, 112, 26, stroke="#555", fill="#e8f0e0", sw=1, rx=2)
        self.text(x + 64, y + 27, reading, 14, anchor="middle", bold=True)
        self.text(x + 64, y + 53, mode, 10.5, anchor="middle", color="#444")

    def code(self, x: float, y: float, line: str, size: float = 13) -> None:
        from xml.sax.saxutils import escape
        self.el.append(f'<text x="{x:.1f}" y="{y:.1f}" font-size="{size}" font-family="Consolas, Courier New, monospace" '
                       f'font-weight="bold" fill="#0d47a1">{escape(line)}</text>')
        w = len(line) * size * 0.55
        self.boxes.append((x, y - size * 0.78, x + w, y + size * 0.22, line))

    def header_strip(self, x: float, y: float, names: list[str], hi: str | None, title: str) -> dict[str, float]:
        """A pin strip (Arduino header) with labels; returns pin x positions."""
        pitch = 34
        self.rect(x, y, pitch * len(names) + 8, 30, stroke="#333", fill="#222", sw=1, rx=2)
        pos = {}
        for i, n in enumerate(names):
            cx = x + 21 + i * pitch
            self.rect(cx - 7, y + 8, 14, 14, stroke="#999", fill="#ffd54f" if n == hi else "#bdbdbd", sw=1)
            self.text(cx, y + 46, n, 10.5, anchor="middle", bold=n == hi, color="#b71c1c" if n == hi else "#000")
            pos[n] = cx
        self.text(x, y + 66, title, 10.5, color="#555")
        return pos


