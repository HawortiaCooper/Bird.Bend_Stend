def c_define(path, name):
    txt = open(path, encoding="utf-8").read()
    m = re.search(r"#define\s+" + name + r"\s+(\S+)", txt)
    if not m:
        fail(f"{name} not found in {path}")
    return m.group(1)


def carr(data):
    if not data:
        return "{0}"
    return "{" + ",".join(f"0x{b:02X}" for b in data) + "}"


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def cbool(b):
    return "true" if b else "false"


def i32(v):
    """C literal of an int32 (INT32_MIN cannot be written as a plain negative literal)."""
    v = int(v)
    if v == -0x80000000:
        return "INT32_MIN"
    return str(v)


def bits(names, table):
    return rc.names_to_bits(list(names), table)


def wire_of(tname, value):
    return rc.pvalue_pack(rc.PTYPE_CODE[tname], value)


def write(name, lines, sha):
    os.makedirs(OUT_DIR, exist_ok=True)
    guard = name.upper().replace(".", "_")
    head = [f"/* GENERATED by 02_FW/tools/gen_test_vectors.py from 00_System/tools/vectors (json) - "
            f"do not edit.", f" * vectors SHA-256 {sha} */", f"#ifndef {guard}", f"#define {guard}",
            '#pragma GCC diagnostic ignored "-Wunused-const-variable"',
            '#pragma GCC diagnostic ignored "-Wunused-variable"',
            "#include <stdbool.h>", "#include <stdint.h>", '#include "payload.h"', ""]
    text = "\n".join(head + lines + ["#endif", ""])
    path = os.path.join(OUT_DIR, name)
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


