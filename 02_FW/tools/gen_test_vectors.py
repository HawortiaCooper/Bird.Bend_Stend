def f32hex(h):
    return int(h, 16)


def gen_units(v):
    out = ["typedef struct { uint32_t spm_bits; int32_t a; int32_t b; } vec_units_t;",
           "typedef struct { uint32_t spm_bits; uint32_t rate; uint32_t cap; } vec_cap_t;"]
    for name, src, a, b in (("VEC_UM2ST", "um_to_steps", "um", "steps"),
                            ("VEC_ST2UM", "steps_to_um", "steps", "um")):
        out.append(f"static const vec_units_t {name}[] = {{")
        for x in v[src]:
            out.append(f"    {{ 0x{f32hex(x['spm_f32_hex']):08X}u, {i32(x[a])}, {i32(x[b])} }},")
        out.append("};")
        out.append(f"#define {name}_N {len(v[src])}u")
    out.append("static const vec_cap_t VEC_CAP[] = {")
    for x in v["rate_cap"]:
        out.append(f"    {{ 0x{f32hex(x['spm_f32_hex']):08X}u, {x['max_step_rate_hz']}u, {x['rate_cap_um_s']}u }},")
    out.append("};")
    out.append(f"#define VEC_CAP_N {len(v['rate_cap'])}u")
    return out


def gen_motion(v):
    """motion_vectors.json (ref_motion.py oracle, M2): ramp cases, stop paths, planner."""
    kinds = {"controlled_stop": 0, "jog": 1}
    paths = {"ISR": 0, "CLEAN": 1, "STRETCH": 2}
    out = ["typedef struct { uint32_t after; int32_t v_um_s; uint8_t kind; } vec_mev_t;",
           "typedef struct { const char *name; float spm; uint32_t f_tick, v, a, d, a_stop, n_steps;",
           "    uint8_t n_ev; const vec_mev_t *ev; uint32_t n_periods; const uint32_t *periods;",
           "    uint64_t sum; uint32_t tol_p, tol_sum; } vec_motion_t;",
           "typedef struct { uint32_t p_ticks; float spm; uint32_t a_stop; double d_steps; uint8_t path; } vec_spath_t;",
           "typedef struct { uint32_t n; double v, a, d; bool tri; uint32_t n_acc, n_cruise, n_dec;",
           "    double v_peak, t; } vec_plan_t;"]
    for k, c in enumerate(v["cases"]):
        out.append(f"static const uint32_t VMP_{k}[] = {{" + ",".join(f"{p}u" for p in c["periods"]) + "};")
        evs = c["events"]
        if evs:
            out.append(f"static const vec_mev_t VME_{k}[] = {{" + ",".join(
                f"{{{e['after_step']}u, {int(e.get('v_um_s', 0))}, {kinds[e['event']]}u}}" for e in evs) + "};")
    out.append("static const vec_motion_t VEC_MOTION[] = {")
    for k, c in enumerate(v["cases"]):
        evs = c["events"]
        out.append(f"    {{ {cstr(c['name'])}, {float(c['steps_per_mm'])!r}f, {c['f_tick']}u, {c['v_um_s']}u, "
                   f"{c['a_um_s2']}u, {c['d_um_s2']}u, {c['a_stop_um_s2'] or 0}u, {c['n_steps']}u, "
                   f"{len(evs)}u, {('VME_' + str(k)) if evs else '0'}, {c['n_periods']}u, VMP_{k}, "
                   f"{c['sum_ticks']}ull, {c['tolerance']['period_ticks']}u, {c['tolerance']['sum_ticks']}u }},")
    out.append("};")
    out.append(f"#define VEC_MOTION_N {len(v['cases'])}u")
    out.append("static const vec_spath_t VEC_SPATH[] = {")
    for x in v["ctrl_stop_paths"]:
        out.append(f"    {{ {x['p_ticks']}u, {float(x['steps_per_mm'])!r}f, {x['a_stop_um_s2']}u, "
                   f"{float(x['d_steps'])!r}, {paths[x['path']]}u }},")
    out.append("};")
    out.append(f"#define VEC_SPATH_N {len(v['ctrl_stop_paths'])}u")
    out.append("static const vec_plan_t VEC_PLAN[] = {")
    for x in v["planner"]:
        out.append(f"    {{ {x['n_steps']}u, {float(x['v_steps_s'])!r}, {float(x['a_steps_s2'])!r}, "
                   f"{float(x['d_steps_s2'])!r}, {cbool(x['kind'] == 'tri')}, {x['n_acc']}u, {x['n_cruise']}u, "
                   f"{x['n_dec']}u, {float(x['v_peak'])!r}, {float(x['t'])!r} }},")
    out.append("};")
    out.append(f"#define VEC_PLAN_N {len(v['planner'])}u")
    return out


def gen_names():
    """Every generated identifier compared with the hand-written ref_codec tables: a missing or
    renamed macro is a compile error, a different value a test failure (IF-001, GF-08)."""
    rows = []

    def add(prefix, items):
        for n, val in items:
            rows.append(f'    {{ "{prefix}{n}", {val}u, (uint32_t)({prefix}{n}) }},')
    add("CMD_", rc.CMD.items())
    add("ST_", rc.STATUS.items())
    add("EV_", rc.EVENT.items())
    add("SC_", rc.STOP_CAUSE.items())
    for prefix, table in (("DF_", rc.DATA_FLAGS), ("DS_", rc.DATA_STATUS), ("FAULT_", rc.FAULTS),
                          ("BLOCK_", rc.BLOCK), ("IO_", rc.IO), ("SYSF_", rc.SYS_FLAGS),
                          ("FEAT_", rc.FEATURES)):
        add(prefix, [(n, 1 << i) for i, n in enumerate(table) if n])
    for prefix, table in (("MS_", rc.MOTION_STATE), ("HP_", rc.HOME_PHASE), ("SRC_", rc.SOURCE),
                          ("RST_", rc.RESET_CAUSE), ("MD_", rc.MOVE_DONE_REASON)):
        add(prefix, [(n, i) for i, n in enumerate(table)])
    add("HF_", [(n, c) for c, n in rc.HOME_FAIL_REASON.items()])
    consts = [("PROTO_MAX_LEN", rc.MAX_LEN), ("PROTO_HEADER_LEN", rc.HEADER_LEN),
              ("PROTO_FRAME_OVERHEAD", rc.OVERHEAD), ("PROTO_INFO_LEN", rc.INFO_LEN),
              ("PROTO_STATUS_LEN", rc.STATUS_LEN), ("PROTO_DATA_LEN", rc.DATA_LEN),
              ("PROTO_EVENT_LEN", rc.EVENT_LEN), ("PROTO_PARAMS_PER_PAGE", rc.PARAMS_PER_PAGE),
              ("PROTO_REBOOT_MAGIC", rc.REBOOT_MAGIC), ("PROTO_PAYLOAD_VERSION", rc.PAYLOAD_VERSION),
              ("PROTO_MAJOR", rc.PROTO_MAJOR), ("PROTO_MINOR", rc.PROTO_MINOR),
              ("PROTO_INTERBYTE_TIMEOUT_MS", rc.INTERBYTE_TIMEOUT_MS)]
    for n, val in consts:
        rows.append(f'    {{ "{n}", {val}u, (uint32_t)({n}) }},')
    for name in rc.CMD:
        rows.append(f'    {{ "CMD_REQ_LEN_{name}", {rc.REQ_LEN[name]}u, (uint32_t)(CMD_REQ_LEN_{name}) }},')
    out = ["#include \"proto_gen.h\"",
           "typedef struct { const char *name; uint32_t expect; uint32_t actual; } vec_name_t;",
           "static const vec_name_t VEC_NAMES[] = {"] + rows + ["};",
                                                              f"#define VEC_NAMES_N {len(rows)}u"]
    return out


