def gate(jsons):
    gen = os.path.join(FW, "src", "gen")
    icd = c_define(os.path.join(gen, "proto_gen.h"), "PROTO_ICD_VERSION").strip('"')
    h = c_define(os.path.join(gen, "params_gen.h"), "PARAM_DICT_HASH")
    h = int(h.rstrip("uUlL"), 16)
    for name, d in jsons.items():
        if d.get("icd_version") != icd:
            fail(f"{name}.json icd_version {d.get('icd_version')} != PROTO_ICD_VERSION {icd} "
                 "(stale generated headers or vectors: Integrator)")
        if int(d.get("param_dict_hash", "0"), 16) != h:
            fail(f"{name}.json param_dict_hash {d.get('param_dict_hash')} != PARAM_DICT_HASH "
                 f"0x{h:08X} (Integrator)")
    for tool in ("gen_params.py", "gen_vectors.py"):
        r = subprocess.run([sys.executable, os.path.join(TOOLS, tool), "--check"], cwd=ROOT,
                           capture_output=True, text=True)
        if r.returncode != 0:
            sys.stderr.write(r.stdout + r.stderr)
            fail(f"{tool} --check failed: generated outputs are stale (Integrator)")
    return icd, h


