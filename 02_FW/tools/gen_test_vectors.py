def gen_crc(v):
    out = ["typedef struct { const char *name; const uint8_t *data; uint16_t len; uint16_t crc; } vec_crc_t;"]
    for i, c in enumerate(v["crc16"]):
        out.append(f"static const uint8_t VCRC_{i}[] = {carr(bytes.fromhex(c['input_hex']))};")
    out.append("static const vec_crc_t VEC_CRC[] = {")
    for i, c in enumerate(v["crc16"]):
        out.append(f"    {{{cstr(c['name'])}, VCRC_{i}, {len(bytes.fromhex(c['input_hex']))}u, {c['crc']}u}},")
    out.append("};")
    out.append(f"#define VEC_CRC_N {len(v['crc16'])}u")
    return out


def info_init(d):
    b = d["build"].encode("ascii").ljust(16, b"\x00")
    return (f"{{ {d['proto_major']}u, {d['proto_minor']}u, {d['payload_version']}u, "
            f"{{{d['fw_version'][0]}u, {d['fw_version'][1]}u, {d['fw_version'][2]}u}}, "
            f"{d['param_dict_hash']}u, {carr(bytes.fromhex(d['uid']))}, {carr(b)}, "
            f"{d['param_count']}u, 0x{bits(d['features'], rc.FEATURES):08X}u }}")


def status_init(d):
    def enum(k, table):
        return rc._enum_code(table, d[k])
    f = {
        "uptime_ms": f"{d['uptime_ms']}u", "t_us": f"{d['t_us']}u",
        "flags": f"0x{bits(d['flags'], rc.DATA_FLAGS):02X}u",
        "motion_state": f"{enum('motion_state', rc.MOTION_STATE)}u",
        "status": f"0x{bits(d['status'], rc.DATA_STATUS):04X}u",
        "faults": f"0x{bits(d['faults'], rc.FAULTS):04X}u",
        "io": f"0x{bits(d['io'], rc.IO):04X}u",
        "home_phase": f"{enum('home_phase', rc.HOME_PHASE)}u",
        "halt_src": f"{enum('halt_src', rc.SOURCE)}u",
        "reset_cause": f"{enum('reset_cause', rc.RESET_CAUSE)}u",
        "sys_flags": f"0x{bits(d['sys_flags'], rc.SYS_FLAGS):02X}u",
        "pos_um": i32(d["pos_um"]), "target_um": i32(d["target_um"]),
        "pos_steps": i32(d["pos_steps"]), "afe_raw_last": i32(d["afe_raw_last"]),
        "pause_src": f"{enum('pause_src', rc.SOURCE)}u",
    }
    for k in rc.STATUS_FIELDS:
        f.setdefault(k, f"{d[k]}u")
    return "{ " + ", ".join(f".{k} = {f[k]}" for k in rc.STATUS_FIELDS) + " }"


def data_init(d):
    return (f"{{ .t_us = {d['t_us']}u, .flags = 0x{bits(d['flags'], rc.DATA_FLAGS):02X}u, "
            f".afe_raw = {i32(d['afe_raw'])}, .setpoint_um = {i32(d['setpoint_um'])}, "
            f".frame_seq = {d['frame_seq']}u, .status = 0x{bits(d['status'], rc.DATA_STATUS):04X}u }}")


def event_init(d):
    return (f"{{ .t_us = {d['t_us']}u, .code = {rc.EVENT[d['code']]}u, .arg = {d['arg']}u, "
            f".value = {i32(d['value'])}, .value2 = {i32(d['value2'])} }}")


def entry_init(e, raw4=None):
    w = raw4 if raw4 is not None else wire_of(e["type"], e["value"])
    return f"{{ {e['id']}u, {rc.PTYPE_CODE[e['type']]}u, {carr(w)} }}"


def req_init(f):
    d = f["decoded"]
    tn = f["type_name"]
    pl = bytes.fromhex(f["payload_hex"])
    t = f["type"]
    if tn == "REBOOT":
        u = f".u.reboot = {{ {d['magic']}u }}"
    elif tn == "GET_ALL_PARAMS":
        u = f".u.page = {{ {d['page']}u }}"
    elif tn == "GET_PARAM":
        u = f".u.get_param = {{ {d['id']}u }}"
    elif tn == "SET_PARAM":
        # INVALID_PADDING: the vector has no numeric value; the wire bytes are the payload's own
        raw4 = pl[3:7] if d.get("value") == "INVALID_PADDING" else None
        u = f".u.set_param = {entry_init(d, raw4)}"
    elif tn == "SET_VALID":
        u = f".u.set_valid = {{ {d['valid']}u }}"
    elif tn == "HOME":
        u = f".u.home = {{ {d['flags']}u }}"
    elif tn == "MOVE_ABS":
        u = f".u.move_abs = {{ {i32(d['target_um'])}, {d['v_um_s']}u, {d['a_um_s2']}u }}"
    elif tn == "JOG":
        u = f".u.jog = {{ {i32(d['v_um_s'])}, {d['a_um_s2']}u, {i32(d['bound_um'])} }}"
    elif tn == "MOVE_UNTIL_LOAD":
        u = (f".u.mul = {{ {i32(d['bound_um'])}, {d['v_um_s']}u, {d['a_um_s2']}u, "
             f"{i32(d['raw_stop'])}, {d['cmp']}u }}")
    elif tn == "STOP":
        u = f".u.stop = {{ {d['mode']}u }}"
    elif rc.REQ_LEN.get(tn, -1) == 0:
        u = ""
    else:
        fail(f"unhandled request vector {f['name']} ({tn})")
    return f"{{ .type = {t}u{', ' + u if u else ''} }}"


RB = {"NACK": 0, "EMPTY": 1, "INFO": 2, "STATUS": 3, "PAGE": 4, "ENTRY": 5, "U32": 6, "U16": 7}


def gen_frames(v):
    frames = v["frames"]
    out = ["enum { VK_REQUEST = 0, VK_RESPONSE = 1, VK_ASYNC = 2, VK_INVALID = 3 };",
           "typedef struct { const char *name; uint8_t fw_to_pc; uint8_t kind; uint8_t type; uint8_t seq;",
           "    uint16_t len; const uint8_t *frame; uint16_t frame_len; const uint8_t *payload;",
           "    bool reencode; const uint8_t *canon; uint16_t canon_len; bool framing_only;",
           "    uint32_t expect_crc_errors; } vec_frame_t;"]
    kinds = {"request": "VK_REQUEST", "response": "VK_RESPONSE", "async": "VK_ASYNC", "invalid": "VK_INVALID"}
    for i, f in enumerate(frames):
        out.append(f"static const uint8_t VF_{i}[] = {carr(bytes.fromhex(f['frame_hex']))};")
        out.append(f"static const uint8_t VP_{i}[] = {carr(bytes.fromhex(f.get('payload_hex', '')))};")
        if f.get("reencode") is False:
            out.append(f"static const uint8_t VC_{i}[] = {carr(bytes.fromhex(f['canonical_payload_hex']))};")
    out.append("static const vec_frame_t VEC_FRAMES[] = {")
    for i, f in enumerate(frames):
        fr = bytes.fromhex(f["frame_hex"])
        re_ = f.get("reencode") is not False
        canon = "0" if re_ else f"VC_{i}"
        clen = 0 if re_ else len(bytes.fromhex(f["canonical_payload_hex"]))
        out.append(
            f"    {{{cstr(f['name'])}, {1 if f['dir'] == 'fw->pc' else 0}u, {kinds[f['kind']]}, "
            f"{f.get('type', '0x00')}u, {f.get('seq', 0)}u, {f.get('len', 0)}u, VF_{i}, {len(fr)}u, VP_{i}, "
            f"{cbool(re_)}, {canon}, {clen}u, {cbool(f.get('framing_only', False))}, "
            f"{f.get('expect', {}).get('crc_errors', 0)}u}},")
    out.append("};")
    out.append(f"#define VEC_FRAMES_N {len(frames)}u")

    # requests -> expected decoder output
    reqs = [(i, f) for i, f in enumerate(frames)
            if f["kind"] == "request" and not f.get("framing_only") and "raw_hex" not in f["decoded"]]
    out.append("typedef struct { uint16_t idx; cmd_req_t r; } vec_req_t;")
    out.append("static const vec_req_t VEC_REQS[] = {")
    for i, f in reqs:
        out.append(f"    {{ {i}u, {req_init(f)} }},")
    out.append("};")
    out.append(f"#define VEC_REQS_N {len(reqs)}u")

    # responses -> expected body description
    resps = []
    for i, f in enumerate(frames):
        if f["kind"] != "response" or f.get("framing_only"):
            continue
        d = f["decoded"]
        tn = f["type_name"]
        st = d["status"]
        if st != "OK":
            resps.append((i, "NACK", rc.STATUS[st], d["detail"], None))
        elif tn == "GET_INFO":
            resps.append((i, "INFO", 0, 0, d["info"]))
        elif tn == "GET_STATUS":
            resps.append((i, "STATUS", 0, 0, d["board_status"]))
        elif tn == "GET_ALL_PARAMS":
            resps.append((i, "PAGE", 0, 0, d))
        elif tn in ("GET_PARAM", "SET_PARAM"):
            resps.append((i, "ENTRY", 0, 0, d["entry"]))
        elif tn == "SET_VALID":
            resps.append((i, "U32", 0, d["t_us"], None))
        elif tn == "ENABLE":
            resps.append((i, "U16", 0, d["settle_ms"], None))
        elif tn == "FAULT_CLEAR":
            resps.append((i, "U16", 0, bits(d["cleared"], rc.FAULTS), None))
        elif len(d) == 1:
            resps.append((i, "EMPTY", 0, 0, None))
        else:
            fail(f"unhandled response vector {f['name']}")
    for k, (i, kind, _, _, obj) in enumerate(resps):
        if kind == "INFO":
            out.append(f"static const info_t VRI_{k} = {info_init(obj)};")
        elif kind == "STATUS":
            out.append(f"static const status_t VRS_{k} = {status_init(obj)};")
        elif kind == "PAGE":
            out.append(f"static const param_entry_t VRP_{k}[] = {{")
            for e in obj["entries"]:
                out.append(f"    {entry_init(e)},")
            out.append("};")
        elif kind == "ENTRY":
            out.append(f"static const param_entry_t VRE_{k} = {entry_init(obj)};")
    out.append("enum { " + ", ".join(f"RB_{k} = {n}" for k, n in RB.items()) + " };")
    out.append("typedef struct { uint16_t idx; uint8_t kind; uint8_t status; uint32_t num;")
    out.append("    const info_t *info; const status_t *st; const param_entry_t *entries;")
    out.append("    uint8_t page, page_count, n; } vec_resp_t;")
    out.append("static const vec_resp_t VEC_RESPS[] = {")
    for k, (i, kind, st, num, obj) in enumerate(resps):
        info = f"&VRI_{k}" if kind == "INFO" else "0"
        sts = f"&VRS_{k}" if kind == "STATUS" else "0"
        ent = f"VRP_{k}" if kind == "PAGE" else (f"&VRE_{k}" if kind == "ENTRY" else "0")
        page = obj["page"] if kind == "PAGE" else 0
        pc = obj["page_count"] if kind == "PAGE" else 0
        n = len(obj["entries"]) if kind == "PAGE" else (1 if kind == "ENTRY" else 0)
        out.append(f"    {{ {i}u, RB_{kind}, {st}u, {num}u, {info}, {sts}, {ent}, {page}u, {pc}u, {n}u }},")
    out.append("};")
    out.append(f"#define VEC_RESPS_N {len(resps)}u")

    datas = [(i, f) for i, f in enumerate(frames) if f["kind"] == "async" and f["type_name"] == "DATA"]
    events = [(i, f) for i, f in enumerate(frames) if f["kind"] == "async" and f["type_name"] == "EVENT"]
    out.append("typedef struct { uint16_t idx; data_t d; } vec_data_t;")
    out.append("static const vec_data_t VEC_DATAS[] = {" +
               ",".join(f"\n    {{ {i}u, {data_init(f['decoded'])} }}" for i, f in datas) + "\n};")
    out.append(f"#define VEC_DATAS_N {len(datas)}u")
    out.append("typedef struct { uint16_t idx; event_t e; } vec_event_t;")
    out.append("static const vec_event_t VEC_EVENTS[] = {" +
               ",".join(f"\n    {{ {i}u, {event_init(f['decoded'])} }}" for i, f in events) + "\n};")
    out.append(f"#define VEC_EVENTS_N {len(events)}u")
    return out


def gen_streams(v):
    out = ["typedef struct { const char *name; uint8_t n_chunks; const uint8_t *const *chunks;",
           "    const uint16_t *chunk_len; bool idle_timeout_at_end; uint8_t n_before; uint8_t n_frames;",
           "    const uint8_t *const *frames; const uint16_t *frame_len;",
           "    uint32_t frames_ok, crc_errors, len_errors, timeout_drops; } vec_stream_t;"]
    for k, s in enumerate(v["streams"]):
        for j, c in enumerate(s["chunks_hex"]):
            out.append(f"static const uint8_t VSC_{k}_{j}[] = {carr(bytes.fromhex(c))};")
        out.append(f"static const uint8_t *const VSC_{k}[] = {{" +
                   ",".join(f"VSC_{k}_{j}" for j in range(len(s["chunks_hex"]))) + "};")
        out.append(f"static const uint16_t VSCL_{k}[] = {{" +
                   ",".join(f"{len(bytes.fromhex(c))}u" for c in s["chunks_hex"]) + "};")
        for j, fx in enumerate(s["expect_frames_hex"]):
            out.append(f"static const uint8_t VSF_{k}_{j}[] = {carr(bytes.fromhex(fx))};")
        nf = len(s["expect_frames_hex"])
        out.append(f"static const uint8_t *const VSF_{k}[] = {{" +
                   (",".join(f"VSF_{k}_{j}" for j in range(nf)) or "0") + "};")
        out.append(f"static const uint16_t VSFL_{k}[] = {{" +
                   (",".join(f"{len(bytes.fromhex(fx))}u" for fx in s["expect_frames_hex"]) or "0") + "};")
    out.append("static const vec_stream_t VEC_STREAMS[] = {")
    for k, s in enumerate(v["streams"]):
        c = s["expect_counters"]
        nb = len(s["expect_frames_before_timeout"]) if s["expect_frames_before_timeout"] is not None else 255
        out.append(f"    {{ {cstr(s['name'])}, {len(s['chunks_hex'])}u, VSC_{k}, VSCL_{k}, "
                   f"{cbool(s['idle_timeout_at_end'])}, {nb}u, {len(s['expect_frames_hex'])}u, VSF_{k}, "
                   f"VSFL_{k}, {c['frames_ok']}u, {c['crc_errors']}u, {c['len_errors']}u, "
                   f"{c['timeout_drops']}u }},")
    out.append("};")
    out.append(f"#define VEC_STREAMS_N {len(v['streams'])}u")
    return out


def gen_check(v, dic):
    if v.get("state_schema") not in ACCEPTED_SCHEMAS:
        fail(f"check_vectors.json state_schema {v.get('state_schema')} not in {ACCEPTED_SCHEMAS} "
             "(update the FW replay: cmd_ctx_t / this script)")
    by_key = {p.key: p for p in dic.params}
    defaults = v["state_defaults"]
    for x in v["vectors"]:
        if set(RETIRED_KEYS) & set(x["state"]):
            fail(f"check vector {x['name']}: retired state key set (state_schema {STATE_SCHEMA})")
    for k in list(defaults) + [k for x in v["vectors"] for k in x["state"]]:
        if k not in STATE_KEYS:
            fail(f"check_vectors.json: unknown state key {k!r} (state_schema {STATE_SCHEMA})")
    out = ["typedef struct { uint16_t id; uint32_t raw; } vec_pov_t;",
           "typedef struct { const char *name;",
           "    uint8_t motion_state; uint16_t enabling_left_ms; bool homed; int32_t pos_um;",
           "    bool estop_latched, estop_input_open; uint32_t estop_closed_ms;",
           "    bool halt_latched;",
           "    uint16_t faults, fault_causes; bool limit_start, limit_end, afe_stale, afe_saturated;",
           "    int32_t raw; bool drv_power, alm_active, nvm_record_valid, paused;",
           "    uint8_t n_par; const vec_pov_t *par;",
           "    uint8_t type; uint8_t seq; const uint8_t *payload; uint16_t len;",
           "    const uint8_t *req_frame; uint16_t req_frame_len;",
           "    uint8_t exp_status; uint16_t exp_detail; const uint8_t *resp_frame; uint16_t resp_len;",
           "    int8_t paused_after; } vec_check_t;"]
    rows = []
    for k, x in enumerate(v["vectors"]):
        st = dict(defaults)
        st.update(x["state"])
        pars = []
        for key, val in st["params"].items():
            if key not in by_key:
                fail(f"check vector {x['name']}: unknown parameter {key}")
            p = by_key[key]
            pars.append((p.id, gen_params.raw_u32(p, val)))
        if pars:
            out.append(f"static const vec_pov_t VCP_{k}[] = {{" +
                       ",".join(f"{{0x{pid:04X}u,0x{raw:08X}u}}" for pid, raw in pars) + "};")
        rq = x["request"]
        pl = bytes.fromhex(rq["payload_hex"])
        out.append(f"static const uint8_t VCQ_{k}[] = {carr(pl)};")
        out.append(f"static const uint8_t VCF_{k}[] = {carr(bytes.fromhex(rq['frame_hex']))};")
        e = x["expect"]
        resp = bytes.fromhex(e.get("response_frame_hex", ""))
        out.append(f"static const uint8_t VCR_{k}[] = {carr(resp)};")
        pa = e.get("paused_after")
        rows.append(
            f"    {{ {cstr(x['name'])}, {rc.MOTION_STATE.index(st['motion_state'])}u, "
            f"{st['enabling_left_ms']}u, {cbool(st['homed'])}, {i32(st['pos_um'])}, "
            f"{cbool(st['estop_latched'])}, {cbool(st['estop_input_open'])}, {st['estop_closed_ms']}u, "
            f"{cbool(st['halt_latched'])}, "
            f"0x{bits(st['faults'], rc.FAULTS):04X}u, 0x{bits(st['fault_causes'], rc.FAULTS):04X}u, "
            f"{cbool(st['limit_start'])}, {cbool(st['limit_end'])}, {cbool(st['afe_stale'])}, "
            f"{cbool(st['afe_saturated'])}, {i32(st['raw'])}, {cbool(st['drv_power'])}, "
            f"{cbool(st['alm_active'])}, {cbool(st['nvm_record_valid'])}, {cbool(st['paused'])}, "
            f"{len(pars)}u, {('VCP_' + str(k)) if pars else '0'}, {rq['type']}u, {rq['seq']}u, VCQ_{k}, "
            f"{len(pl)}u, VCF_{k}, {len(bytes.fromhex(rq['frame_hex']))}u, {rc.STATUS[e['status']]}u, "
            f"{e['detail']}u, VCR_{k}, {len(resp)}u, {-1 if pa is None else int(bool(pa))} }},")
